def year(y):
    return f"前{-y}" if y < 0 else str(y)


def scene(title, start, end, ticks, events, answer, rows):
    """横長 L 760x400。x = 140 + (年-開始)*600/(終了-開始)。行 i の帯 y = 78 + 52*i、高さ 32。

    描く順：目盛 → 帯 → 同期線 → 文字（線が文字を隠さないように）。
    """
    s = SVG(760, 400, title)
    X = lambda y: 140 + (y - start) * 600 / (end - start)
    bands = [(i, max(a, start), min(b, end), label, mark)
             for i, (_, periods) in enumerate(rows) for a, b, label, mark in periods
             if min(b, end) > max(a, start)]
    for t in ticks:
        s.line(X(t), 70, X(t), 336, stroke="#e6e6e6")
        s.text(X(t), 356, year(t), size=14, fill=SUB, anchor="middle")
    for i, a, b, label, mark in bands:
        col = {1: MAIN, 2: FOCUS, 0: MUTED}[mark]
        s.rect(X(a), 78 + 52 * i, X(b) - X(a), 32, fill=TINT[col] if mark else "#ffffff", stroke=col,
               sw=1.8 if mark else 1)
        assert X(b) - X(a) >= len(label) * 15 + 8, f"{label} が帯に入らない"
    for k, (y, _) in enumerate(events):
        s.line(X(y), 50 + 16 * (k % 2), X(y), 336, stroke=INK, sw=1.6, dash="5 4")
    for i, (region, _) in enumerate(rows):
        s.text(126, 78 + 52 * i + 22, region, size=15, anchor="end", bold=i == 0)
    for i, a, b, label, mark in bands:
        s.text((X(a) + X(b)) / 2, 78 + 52 * i + 22, label, size=15, anchor="middle", bold=mark == 1,
               fill=INK if mark else SUB, halo=True)
    for k, (y, name) in enumerate(events):
        s.text(X(y), 42 + 16 * (k % 2), f"{year(y)} {name}", size=14, anchor="middle", bold=True,
               halo=True)
    s.note(140, 390, answer)
    return s


if __name__ == "__main__":
    sys.exit(build({OUT / f"{name}.svg": (lambda a=args: scene(*a))
                    for name, *args in SCENES}))
